export function resolveReadingProse(draft: Draft, matches: readonly ReadingMatch[], aliases: readonly string[] = []): { title: string; opening: string; paragraphs: ReadingParagraph[] } {
  const paragraphs = draft.paragraphs.flatMap(item => {
    const sources = item.basis.map(basis => matches.find(match => match.entry.day === basis.day &&
      readingTexts(match.entry).flatMap(readingSentences).some(sentence => sentence.includes(basis.needle) &&
        (!aliases.length || aliases.some(alias => sentence.includes(alias))))));
    return sources.every((source): source is ReadingMatch => !!source)
      ? [{ text: item.text, sources: [...new Map(sources.map(source => [source.entry.day, source])).values()] }] : [];
  });
  return { title: draft.title, opening: draft.opening, paragraphs };
}
